#!/usr/bin/env python3
"""Generates src/crt/ucrt_math_tab.h: the binary expansion of 2/pi for the Payne-Hanek argument reduction of
huge arguments, and pi/2 split into 30-bit pieces for the Cody-Waite reduction of moderate ones.

Everything is computed with Python integers (Machin's formula), so there is no dependence on a math library.
Run: python3 build/gen_ucrt_math_tab.py > src/crt/ucrt_math_tab.h
"""
import sys

PREC = 2600  # bits of working precision


def arctan_inv(n, one):
    """arctan(1/n) scaled by `one`."""
    n2 = n * n
    term = one // n
    total = term
    k = 1
    while term:
        term //= n2
        k += 2
        total += term // k if (k // 2) % 2 == 0 else -(term // k)
    return total


def pi_fixed(bits):
    one = 1 << (bits + 32)
    pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
    return pi >> 32  # pi * 2^bits


def zeta_table():
    """zeta(k) for k = 2..40 (and zeta(k) - 1), computed with Euler-Maclaurin summation in decimal arithmetic,
    for the Taylor series of lgamma around 1 and 2."""
    from decimal import Decimal, getcontext
    from fractions import Fraction
    getcontext().prec = 80
    # Bernoulli numbers B_0 .. B_30 as Fractions
    B = [Fraction(0)] * 31
    B[0] = Fraction(1)
    from math import comb
    for m in range(1, 31):
        B[m] = -sum(comb(m + 1, j) * B[j] for j in range(m)) / (m + 1)
    N = 60

    def zeta(k):
        total = Decimal(0)
        for n in range(1, N):
            total += Decimal(1) / (Decimal(n) ** k)
        Nd = Decimal(N)
        total += Nd ** (1 - k) / (k - 1) + (Nd ** -k) / 2
        fact = Fraction(1)
        for j in range(1, 14):
            # B_{2j}/(2j)! * k (k+1) ... (k+2j-2) * N^{-k-2j+1}
            fact = Fraction(1)
            for i in range(2 * j):
                fact /= (i + 1)
            rising = Fraction(1)
            for i in range(2 * j - 1):
                rising *= (k + i)
            coeff = B[2 * j] * fact * rising
            total += Decimal(coeff.numerator) / Decimal(coeff.denominator) * Nd ** (-k - 2 * j + 1)
        return total

    lines = []
    lines.append("")
    lines.append("/* zeta(k) - 1 for k = 2..41, for the Taylor series of lgamma about 1 and 2. */")
    lines.append("#define UCRT_ZETA_COUNT 40")
    lines.append("static const long double ucrt_zeta_m1[UCRT_ZETA_COUNT] = {")
    vals = []
    for k in range(2, 42):
        z = zeta(k) - 1
        vals.append(format(z, ".28e") + "L")
    for i in range(0, len(vals), 2):
        lines.append("    " + ", ".join(vals[i:i + 2]) + ",")
    lines.append("};")
    lines.append("#define UCRT_EULER_GAMMA_L 0.577215664901532860606512090082402431042L")
    return lines


def main():
    pi = pi_fixed(PREC)
    # 2/pi * 2^N, with N bits after the point
    n_bits = 1280
    two_over_pi = (2 << (PREC + n_bits)) // pi  # floor(2/pi * 2^n_bits)
    assert 0 < two_over_pi < (1 << n_bits)
    words = []
    for i in range(n_bits // 32):
        shift = n_bits - 32 * (i + 1)
        words.append((two_over_pi >> shift) & 0xFFFFFFFF)

    out = []
    out.append("/* Generated by build/gen_ucrt_math_tab.py; do not edit. */")
    out.append("#ifndef UCRT_MATH_TAB_H")
    out.append("#define UCRT_MATH_TAB_H")
    out.append("")
    out.append("/* The binary expansion of 2/pi after the point, 32 bits per word, most significant first: bit i of the")
    out.append(" * expansion (counting from 1) has weight 2^-i. */")
    out.append("#define UCRT_TWO_OVER_PI_WORDS %d" % len(words))
    out.append("static const uint32_t ucrt_two_over_pi[UCRT_TWO_OVER_PI_WORDS] = {")
    for i in range(0, len(words), 6):
        out.append("    " + ", ".join("0x%08xu" % w for w in words[i:i + 6]) + ",")
    out.append("};")
    out.append("")

    # pi/2 in four pieces of 30 bits each (the last carries the rest), as long double hex constants.
    half = pi >> 1  # pi/2 * 2^PREC, in [1, 2)
    pieces = []
    rem = half
    scale = PREC
    for k in range(4):
        # take the next 30 bits below the current weight
        bits = 31 if k == 0 else 30
        sh = scale - (bits - 1) if k == 0 else scale - bits
        # integer of `bits` bits
        piece = rem >> sh
        rem -= piece << sh
        pieces.append((piece, sh))
        scale = sh
    out.append("/* pi/2 = p1 + p2 + p3 + p4, each of 30 or 31 significant bits, so n*pj is exact for n < 2^33. */")
    for k, (piece, sh) in enumerate(pieces):
        # value = piece * 2^(sh - PREC)
        e = sh - PREC
        out.append("#define UCRT_PIO2_%d 0x%xp%dL" % (k + 1, piece, e))
    # the whole of pi/2 and pi to long double precision (64 bits)
    for name, val in (("PIO2", half), ("PI", pi)):
        bl = val.bit_length()
        top64 = val >> (bl - 64)
        # round to nearest
        if (val >> (bl - 65)) & 1:
            top64 += 1
        e = (bl - 64) - PREC
        out.append("#define UCRT_%s_LD 0x%xp%dL" % (name, top64, e))
    out.append("")
    # ln2 = hi + lo, with hi of 32 significant bits so that k*hi is exact for |k| < 2^31
    ln2 = 0
    one = 1 << PREC
    for k in range(1, PREC + 1):
        ln2 += one // (k << k)
    bl = ln2.bit_length()
    hi = (ln2 >> (bl - 32)) << (bl - 32)
    lo = ln2 - hi
    out.append("/* ln 2 = hi + lo; hi has 32 significant bits, so k*hi is exact in extended precision. */")
    out.append("#define UCRT_LN2_HI_L 0x%xp%dL" % (hi >> (bl - 32), (bl - 32) - PREC))
    lbl = lo.bit_length()
    top64 = lo >> (lbl - 64)
    if (lo >> (lbl - 65)) & 1:
        top64 += 1
    out.append("#define UCRT_LN2_LO_L 0x%xp%dL" % (top64, (lbl - 64) - PREC))
    out.append("")
    out.extend(zeta_table())
    out.append("")
    out.append("#endif /* UCRT_MATH_TAB_H */")
    sys.stdout.write("\n".join(out) + "\n")


main()
