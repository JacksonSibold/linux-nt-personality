#!/usr/bin/env python3
"""Writes src/ntdll/rtl/nls_tables.h: single-byte code pages and the case mapping tables for the Rtl conversion functions.

The data comes from the NLS files of a Wine checkout (the nls/ directory: c_<codepage>.nls and l_intl.nls). Wine builds
those from the Unicode Consortium mapping tables so that they match the Windows tables; its unit tests check the results
against Windows. The generated header is checked in, so building the project does not need Wine.

  python3 build/gen_nls_tables.py WINE_NLS_DIR

WINE_NLS_DIR is the nls directory of the Wine commit named in docs/policy/THIRD-PARTY.md.

File formats (Wine dlls/ntdll/locale_private.h):
  c_N.nls  header (13 words: header size, code page, max char size, default char, Unicode default char,
           translation default char, translation Unicode default char, lead bytes), then the table to Unicode (offset of
           the other table, 256 words), glyph table, DBCS ranges, and the table from Unicode (type word, 65536 entries).
  l_intl.nls  version, offset of the lower case table, then both case tables as three-level 16-bit offset tables.
"""
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "ntdll" / "rtl" / "nls_tables.h"

# Single-byte code pages to include.
PAGES = [
    437, 720, 737, 775, 850, 852, 855, 857, 860, 861, 862, 863, 864, 865, 866, 869, 874,
    1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258, 10000, 20127, 20866, 21866,
    28591, 28592, 28593, 28594, 28595, 28596, 28597, 28598, 28599, 28603, 28605,
]


def words(path):
    data = path.read_bytes()
    return struct.unpack("<%dH" % (len(data) // 2), data)


def read_page(path):
    w = words(path)
    hdr = w[0]
    info = {"cp": w[1], "maxchar": w[2], "def": w[3], "unidef": w[4], "transdef": w[5], "transunidef": w[6]}
    if info["maxchar"] != 1:
        raise SystemExit("%s is not a single-byte page" % path.name)
    p = hdr
    cp2uni = list(w[p + 1:p + 257])
    uni2cp_off = p + w[p]
    kind = w[uni2cp_off]
    if kind != 0:
        raise SystemExit("%s: unexpected table type %d" % (path.name, kind))
    # 65536 bytes follow the type word, packed two to a word.
    raw = struct.pack("<%dH" % 32768, *w[uni2cp_off + 1:uni2cp_off + 1 + 32768])
    uni2cp = raw
    pairs = []
    for wc in range(0x10000):
        mb = uni2cp[wc]
        if mb == info["def"] and wc != info["unidef"]:
            continue
        if wc < 0x80 and mb == wc:
            continue
        pairs.append((wc, mb))
    info["cp2uni"] = cp2uni
    info["pairs"] = pairs
    return info


def emit_array(out, ctype, name, values, per_line, fmt):
    out.append("static const %s %s[%d] = {" % (ctype, name, len(values)))
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(fmt % v for v in values[i:i + per_line]) + ",")
    out.append("};")


def build(nls_dir):
    out = [
        "/*",
        " * nls_tables.h - single-byte code pages and case mapping for the Rtl conversion functions (nls.c).",
        " *",
        " * Generated by build/gen_nls_tables.py from the NLS files of Wine (nls/c_*.nls and nls/l_intl.nls, LGPL-2.1-or-later;",
        " * see docs/policy/THIRD-PARTY.md). Do not edit by hand.",
        " *",
        " * A page gives the Unicode value of each byte and the pairs (Unicode value, byte) of every character that is not",
        " * the default character, apart from ASCII mapped to itself, in order of Unicode value. These are the Windows tables,",
        " * best-fit mappings included.",
        " */",
        "#ifndef NTDLL_RTL_NLS_TABLES_H",
        "#define NTDLL_RTL_NLS_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "struct nls_pair { uint16_t wc; uint8_t mb; };",
        "",
        "struct nls_sbcs {",
        "    unsigned int cp;",
        "    uint16_t default_char;          /* the byte written for a character the page lacks */",
        "    uint16_t uni_default_char;      /* the character read for a byte the page lacks */",
        "    const uint16_t *to_wc;          /* 256 entries */",
        "    const struct nls_pair *to_mb;   /* sorted by wc */",
        "    unsigned int to_mb_count;",
        "};",
        "",
    ]
    infos = []
    for cp in PAGES:
        info = read_page(nls_dir / ("c_%d.nls" % cp))
        infos.append(info)
        out.append("/* code page %d */" % cp)
        emit_array(out, "uint16_t", "nls_cp%d_wc" % cp, info["cp2uni"], 8, "0x%04X")
        out.append("static const struct nls_pair nls_cp%d_mb[%d] = {" % (cp, len(info["pairs"])))
        pairs = info["pairs"]
        for i in range(0, len(pairs), 6):
            out.append("    " + ", ".join("{0x%04X, 0x%02X}" % p for p in pairs[i:i + 6]) + ",")
        out.append("};")
        out.append("")
    out.append("static const struct nls_sbcs nls_sbcs_pages[%d] = {" % len(infos))
    for info in infos:
        cp = info["cp"]
        out.append("    {%d, 0x%02X, 0x%04X, nls_cp%d_wc, nls_cp%d_mb, %d}," % (
            cp, info["def"], info["unidef"], cp, cp, len(info["pairs"])))
    out.append("};")
    out.append("")
    case = words(nls_dir / "l_intl.nls")
    out.append("/* case mapping: upper = nls_casemap + 2, lower = nls_casemap + 2 + nls_casemap[1];")
    out.append("   map(table, ch) = ch + table[table[table[ch >> 8] + ((ch >> 4) & 0xf)] + (ch & 0xf)] */")
    emit_array(out, "uint16_t", "nls_casemap", case, 12, "0x%04X")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    text = build(Path(sys.argv[1]))
    OUT.write_text(text)
    print("wrote %s (%d bytes)" % (OUT.relative_to(ROOT), len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
