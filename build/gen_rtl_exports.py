#!/usr/bin/env python3
"""Writes src/ntdll/rtl/rtl_exports.txt: the ntdll.dll exports that the objects of src/ntdll/rtl define.

  python3 build/gen_rtl_exports.py WINE_NTDLL_SPEC OBJECT...

WINE_NTDLL_SPEC is dlls/ntdll/ntdll.spec of the Wine commit named in docs/policy/THIRD-PARTY.md. An entry of the spec is
`@ stdcall Name(args) Target`, with Target left out when it is the same as Name. The line written is `Name` or `Name=Target`
(the format of src/ntdll/ntdll_exports.txt) for every entry whose target symbol one of the objects defines. Entries for
the 32-bit ABI only (-arch=i386, -arch=arm...) are skipped. Run it with the x86_64 MinGW objects of src/ntdll/out.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "ntdll" / "rtl" / "rtl_exports.txt"

spec, objs = Path(sys.argv[1]), sys.argv[2:]

defined = set()
for obj in objs:
    res = subprocess.run(["x86_64-w64-mingw32-nm", "-g", "--defined-only", obj], capture_output=True, text=True, check=True)
    for line in res.stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TtDdBb":
            defined.add(parts[2])

entry = re.compile(r"^@\s+(stdcall|cdecl|fastcall|varargs|stub|extern|thiscall)\s+((?:-\w+(?:=[\w,|]+)?\s+)*)([^\s(]+)(?:\([^)]*\))?\s*(\S*)\s*$")
lines = []
for raw in spec.read_text().splitlines():
    m = entry.match(raw.strip())
    if not m:
        continue
    kind, flags, name, target = m.groups()
    arch = re.search(r"-arch=([\w,|]+)", flags)
    if arch and "x86_64" not in arch.group(1).replace("|", ",").split(","):
        continue
    if kind in ("stub", "extern"):
        continue
    sym = target or name
    if sym not in defined:
        continue
    lines.append(name if sym == name else "%s=%s" % (name, sym))

header = """# Exports of ntdll.dll that the Rtl library of src/ntdll/rtl defines. One name per line, or name=target for an alias.
# Generated by build/gen_rtl_exports.py from Wine's ntdll.spec and the objects of src/ntdll/rtl. Read by build/gen_ntdll_def.py.
"""
OUT.write_text(header + "\n".join(sorted(set(lines), key=str.lower)) + "\n")
print("wrote %s: %d exports" % (OUT.relative_to(ROOT), len(set(lines))))
