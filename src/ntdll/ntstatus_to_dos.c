/*
 * ntstatus_to_dos.c
 *
 * RtlNtStatusToDosError implementation for the x86-64 NT personality.
 *
 * This table is the single source of truth for converting kernel-returned
 * NTSTATUS values into the Win32 error codes that user-mode Win32 layers
 * expose via GetLastError().  The mapping is canonical Microsoft reference
 * data; any entry we were unsure of is marked UNVERIFIED and is listed
 * in the project report.
 *
 * Critical correctness trap (do not collapse):
 *   STATUS_BUFFER_OVERFLOW  (0x80000005) -> ERROR_MORE_DATA        (234)
 *   STATUS_BUFFER_TOO_SMALL (0xC0000023) -> ERROR_INSUFFICIENT_BUFFER (122)
 *
 * The table is sorted by NTSTATUS so that the lookup can use binary search.
 */

