#define NTSTATUS_TO_DOS_COUNT (sizeof(NtStatusToDosErrorTable) / sizeof(NtStatusToDosErrorTable[0]))

/* Fallback value used by Windows for unmapped NTSTATUS values. */
#define ERROR_MR_MID_NOT_FOUND                317L

/*
 * Fallback matching real ntdll (Wine's RtlNtStatusToDosErrorNoTeb):
 * - zero or customer-bit set -> return Status itself
 * - 0xD... -> strip 0x10000000 (customer alias)
 * - HIWORD 0xC001 / 0x8007 / 0xC007 -> LOWORD (FACILITY_NTWIN32 and FACILITY 1 error)
 * - otherwise -> 317
 * Table lookup is done before calling this; this is only for misses.
 */
static ULONG __attribute__((unused)) RtlNtStatusToDosErrorFallback(NTSTATUS Status)
{
    ULONG st = (ULONG)Status;
    if (!st) return 0;
    if (st & 0x20000000UL) return st;
    if ((st & 0xF0000000UL) == 0xD0000000UL) {
        st &= ~0x10000000UL;
        Status = (NTSTATUS)st;
    }
    ULONG hi = (st >> 16) & 0xFFFFUL;
    if (hi == 0xC001UL || hi == 0x8007UL || hi == 0xC007UL) {
        return st & 0xFFFFUL;
    }
    return ERROR_MR_MID_NOT_FOUND;
}

/*
 * Binary-search the canonical table.  Falls back to the Windows-compatible
 * generic algorithm for any status not explicitly listed.
 */
ULONG RtlNtStatusToDosError(NTSTATUS Status)
{
    LONG lo = 0;
    LONG hi = (LONG)NTSTATUS_TO_DOS_COUNT - 1;

    while (lo <= hi) {
        LONG mid = lo + (hi - lo) / 2;
        if (NtStatusToDosErrorTable[mid].Status == Status) {
            return NtStatusToDosErrorTable[mid].DosError;
        }
        if (NtStatusToDosErrorTable[mid].Status < Status) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }

    return RtlNtStatusToDosErrorFallback(Status);
}
