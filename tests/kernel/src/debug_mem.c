void _start(){
    __asm__ volatile(
        "sub $128, %%rsp\n"
        "xor %%rax, %%rax\n"
        "mov %%rax, 0x00(%%rsp)\n"
        "mov $0x10000, %%rax\n"
        "mov %%rax, 0x08(%%rsp)\n"
        "mov $-1, %%r10\n"
        "lea 0x00(%%rsp), %%rdx\n"
        "xor %%r8, %%r8\n"
        "lea 0x08(%%rsp), %%r9\n"
        "mov $0x2000, %%rax\n"
        "mov %%rax, 0x28(%%rsp)\n"
        "mov $0x04, %%rax\n"
        "mov %%rax, 0x30(%%rsp)\n"
        "mov $0x18, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail1\n"
        "mov 0x00(%%rsp), %%rbx\n" // base
        // query
        "mov $-1, %%r10\n"
        "mov %%rbx, %%rdx\n"
        "xor %%r8, %%r8\n"
        "lea 0x20(%%rsp), %%r9\n"
        "mov $48, %%rax\n"
        "mov %%rax, 0x28(%%rsp)\n"
        "lea 0x60(%%rsp), %%rax\n"
        "mov %%rax, 0x30(%%rsp)\n"
        "mov $0x23, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail2\n"
        // check state = 0x2000
        "mov 0x40(%%rsp), %%eax\n" // State at 0x20+0x20=0x40
        "cmp $0x2000, %%eax\n"
        "jne fail3\n"
        // commit one page
        "mov %%rbx, 0x00(%%rsp)\n"
        "mov $0x1000, %%rax\n"
        "mov %%rax, 0x08(%%rsp)\n"
        "mov $-1, %%r10\n"
        "lea 0x00(%%rsp), %%rdx\n"
        "xor %%r8, %%r8\n"
        "lea 0x08(%%rsp), %%r9\n"
        "mov $0x1000, %%rax\n"
        "mov %%rax, 0x28(%%rsp)\n"
        "mov $0x04, %%rax\n"
        "mov %%rax, 0x30(%%rsp)\n"
        "mov $0x18, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail4\n"
        // query again should be COMMIT 0x1000
        "mov $-1, %%r10\n"
        "mov %%rbx, %%rdx\n"
        "xor %%r8, %%r8\n"
        "lea 0x20(%%rsp), %%r9\n"
        "mov $48, %%rax\n"
        "mov %%rax, 0x28(%%rsp)\n"
        "lea 0x60(%%rsp), %%rax\n"
        "mov %%rax, 0x30(%%rsp)\n"
        "mov $0x23, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail5\n"
        "mov 0x40(%%rsp), %%eax\n"
        "cmp $0x1000, %%eax\n"
        "jne fail6\n"
        // protect to RO
        "mov %%rbx, 0x00(%%rsp)\n"
        "mov $0x1000, %%rax\n"
        "mov %%rax, 0x08(%%rsp)\n"
        "mov $-1, %%r10\n"
        "lea 0x00(%%rsp), %%rdx\n"
        "lea 0x08(%%rsp), %%r8\n"
        "mov $0x02, %%r9\n"
        "lea 0x10(%%rsp), %%rax\n"
        "mov %%rax, 0x28(%%rsp)\n"
        "mov $0x50, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail7\n"
        // decommit
        "mov %%rbx, 0x00(%%rsp)\n"
        "mov $0x1000, %%rax\n"
        "mov %%rax, 0x08(%%rsp)\n"
        "mov $-1, %%r10\n"
        "lea 0x00(%%rsp), %%rdx\n"
        "lea 0x08(%%rsp), %%r8\n"
        "mov $0x4000, %%r9\n"
        "mov $0x1e, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail8\n"
        // release
        "mov %%rbx, 0x00(%%rsp)\n"
        "mov $0, %%rax\n"
        "mov %%rax, 0x08(%%rsp)\n"
        "mov $-1, %%r10\n"
        "lea 0x00(%%rsp), %%rdx\n"
        "lea 0x08(%%rsp), %%r8\n"
        "mov $0x8000, %%r9\n"
        "mov $0x1e, %%eax\n"
        "syscall\n"
        "test %%eax, %%eax\n"
        "jnz fail9\n"
        "mov $0x2c, %%eax\n"
        "mov $-1, %%r10\n"
        "xor %%rdx, %%rdx\n"
        "syscall\n"
        "hlt\n"
        "fail1: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $1, %%rdx\n syscall\n hlt\n"
        "fail2: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $2, %%rdx\n syscall\n hlt\n"
        "fail3: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $3, %%rdx\n syscall\n hlt\n"
        "fail4: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $4, %%rdx\n syscall\n hlt\n"
        "fail5: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $5, %%rdx\n syscall\n hlt\n"
        "fail6: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $6, %%rdx\n syscall\n hlt\n"
        "fail7: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $7, %%rdx\n syscall\n hlt\n"
        "fail8: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $8, %%rdx\n syscall\n hlt\n"
        "fail9: mov $0x2c, %%eax\n mov $-1, %%r10\n mov $9, %%rdx\n syscall\n hlt\n"
        ::: "rax","rbx","rcx","rdx","r8","r9","r10","r11","memory","cc"
    );
}
