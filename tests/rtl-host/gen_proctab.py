#!/usr/bin/env python3
"""Writes proctab.c: the table behind GetProcAddress(GetModuleHandle("ntdll.dll"), name) in the Rtl host tests.

Usage: gen_proctab.py OUT.c OBJ.o...

The table lists every global function symbol of the objects whose name starts with Rtl, Nt, Zw, Ldr, Dbg or ntdll_.
A name with the host prefix ntdll_ (the renamed C library functions, see src/ntdll/rtl/compat/host_rename.h) is entered
without the prefix, as the test looks for it by its Windows name; so is a name that printf.c spells NTDLL_xxx.
"""
import re
import subprocess
import sys

out, objs = sys.argv[1], sys.argv[2:]
names = {}
for obj in objs:
    for line in subprocess.run(["nm", "-g", "--defined-only", obj], capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TtDd" and re.match(r"^(Rtl|Nt|Zw|Ldr|Dbg|Etw|WinSqm|ntdll_)", parts[2]):
            sym = parts[2]
            name = sym[6:] if sym.startswith("ntdll_") else sym
            # printf.c names the functions that clash with compiler builtins NTDLL_xxx; the spec exports them as xxx.
            if name.startswith("NTDLL_"):
                name = name[6:]
            names[name] = sym

with open(out, "w") as f:
    f.write("/* Generated by gen_proctab.py. Do not edit. */\n")
    f.write("struct rtl_proc { const char *name; void *addr; };\n")
    for sym in sorted(set(names.values())):
        f.write("extern char %s[];\n" % sym)
    f.write("const struct rtl_proc rtl_proc_table[] = {\n")
    for name in sorted(names):
        f.write('    {"%s", %s},\n' % (name, names[name]))
    f.write("    {0, 0}\n};\n")
