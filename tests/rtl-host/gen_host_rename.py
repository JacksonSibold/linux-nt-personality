#!/usr/bin/env python3
"""Writes src/ntdll/rtl/compat/host_rename.h.

The ported string.c, wcstring.c and printf.c define the C library functions that ntdll.dll exports, with 16-bit wide
characters. In the DLL they take the place of the MinGW library. In the host tests the native C library has the same
names with a 32-bit wchar_t, so this header renames them (ntdll_ prefix) and declares them with the signatures from the
sources, which keeps a use before the definition from becoming an implicit declaration.

Usage: gen_host_rename.py [repo-root]
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2]
rtl = root / "src" / "ntdll" / "rtl"
files = ["string.c", "wcstring.c", "printf.c", "nls.c", "misc.c"]

sig_re = re.compile(
    r"^(?P<sig>(?:[A-Za-z_][A-Za-z_0-9 \*]*?)\b(?:__cdecl|WINAPIV|CDECL)\s+\**\s*(?P<name>[A-Za-z_][A-Za-z_0-9]*)\s*\((?P<args>[^{;]*?)\))\s*\n?\s*\{",
    re.M,
)

defs = {}
for fn in files:
    text = re.sub(r"/\*.*?\*/", " ", (rtl / fn).read_text(), flags=re.S)
    for m in sig_re.finditer(text):
        name = m.group("name")
        if name.startswith(("Rtl", "Etw")):
            continue
        sig = " ".join(m.group("sig").split())
        if re.match(r"(static|extern)\b", sig):
            continue
        sig = re.sub(r"\bDECLSPEC_HOTPATCH\b\s*", "", sig)
        defs.setdefault(name, sig)

out = [
    "/*",
    " * host_rename.h - renames and declarations of the C library functions defined by the ported string.c, wcstring.c and",
    " * printf.c, for the host test build only. Generated by tests/rtl-host/gen_host_rename.py; do not edit by hand.",
    " */",
    "#ifndef RTL_COMPAT_HOST_RENAME_H",
    "#define RTL_COMPAT_HOST_RENAME_H",
    "",
]
for name in sorted(defs):
    out.append("#undef %s" % name)
    out.append("#define %s ntdll_%s" % (name, name))
out.append("")
for name in sorted(defs):
    out.append(defs[name] + ";")
out.append("")
out.append("#endif")
(rtl / "compat" / "host_rename.h").write_text("\n".join(out) + "\n")
print("%d functions" % len(defs))
