#!/usr/bin/env python3
"""Writes nt_stubs.c: a weak definition of every system call stub in src/ntdll/syscall_table.def, returning
STATUS_NOT_IMPLEMENTED, for the host link. host_support.c defines the few that the tests need, and its strong definitions win.

Usage: gen_nt_stubs.py SYSCALL_TABLE.def OUT.c
"""
import re
import sys
from pathlib import Path

names = re.findall(r"NT_SYSCALL\s*\(\s*(Nt\w+)\s*,", Path(sys.argv[1]).read_text())
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by gen_nt_stubs.py. Do not edit. */\n")
    f.write("#define NOT_IMPLEMENTED 0xC0000002\n")
    for n in names:
        zw = "Zw" + n[2:]
        f.write("__attribute__((weak)) int %s(void) { return NOT_IMPLEMENTED; }\n" % n)
        f.write("__attribute__((weak)) int %s(void) { return NOT_IMPLEMENTED; }\n" % zw)
