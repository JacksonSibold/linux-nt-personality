#!/usr/bin/env python3
"""Generate docs/status/DRIVERHOST-EXPORTS.md for the NT kernel-mode driver host.

Inputs (both in the repository):
  src/kernel/nt/driver/drvhost_exports.c   the implemented exports, one X_NT/X_HAL row each
  tools/ntos_common_imports.txt            WDK export names ranked by import frequency

The output lists, for every ranked name, whether the driver host implements it,
then the implemented exports that are not in the ranking.  The output has no
timestamps, so regenerating it on an unchanged tree gives identical bytes.

Usage:
  python tools/gen_ntos_surface.py --repo <repo root> --out docs/status/DRIVERHOST-EXPORTS.md
  python tools/gen_ntos_surface.py --repo <repo root> --check   (exit 1 if the file is stale)

Standard library only.
"""
import argparse
import os
import re
import sys

EXPORTS_REL = os.path.join("src", "kernel", "nt", "driver", "drvhost_exports.c")
MANIFEST_REL = os.path.join("tools", "ntos_common_imports.txt")
OUT_REL = os.path.join("docs", "status", "DRIVERHOST-EXPORTS.md")

# Export rows: X_NT("Name", host_fn) or X_HAL("Name", host_fn).
ROW_RE = re.compile(r'^\s*X_(NT|HAL)\("([^"]+)",\s*([A-Za-z_][A-Za-z0-9_]*)\)')

# Exports that are variables (the import thunk holds their address).
DATA_EXPORTS = {
    "PsThreadType", "IoFileObjectType", "IoDeviceObjectType", "ExEventObjectType",
    "NtBuildNumber", "KeNumberProcessors",
}

MODULE_NAME = {"ntoskrnl": "ntoskrnl.exe", "hal": "hal.dll"}


def read_implemented(path):
    """Returns {(module, name): host_symbol} for the X_NT / X_HAL rows."""
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = ROW_RE.match(line)
            if not m:
                continue
            module = "ntoskrnl" if m.group(1) == "NT" else "hal"
            key = (module, m.group(2))
            if key in out:
                raise SystemExit(f"duplicate implemented export {key} in {path}")
            out[key] = m.group(3)
    if not out:
        raise SystemExit(f"no export rows found in {path}")
    return out


def read_manifest(path):
    """Returns a list of (tier, module, name) in ranking order."""
    rows = []
    seen = set()
    with open(path, encoding="utf-8") as f:
        for lineno, raw in enumerate(f, 1):
            line = raw.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) != 3:
                raise SystemExit(f"{path}:{lineno}: expected tier<TAB>module<TAB>name")
            tier, module, name = parts
            if module not in MODULE_NAME:
                raise SystemExit(f"{path}:{lineno}: unknown module {module!r}")
            if not tier.isdigit():
                raise SystemExit(f"{path}:{lineno}: tier must be a number")
            if (module, name) in seen:
                raise SystemExit(f"{path}:{lineno}: duplicate {module}!{name}")
            seen.add((module, name))
            rows.append((int(tier), module, name))
    return rows


def build(repo):
    implemented = read_implemented(os.path.join(repo, EXPORTS_REL))
    ranked = read_manifest(os.path.join(repo, MANIFEST_REL))
    ranked_keys = {(m, n) for _, m, n in ranked}

    lines = []
    add = lines.append
    add("# NT kernel-mode driver host: ntoskrnl and hal export surface")
    add("")
    add("<!-- Generated by tools/gen_ntos_surface.py. Do not edit by hand. -->")
    add("<!-- Regenerate: python tools/gen_ntos_surface.py --repo . --out docs/status/DRIVERHOST-EXPORTS.md -->")
    add("")
    add("The driver host (`src/kernel/nt/driver/`) loads a native x64 `.sys`, binds its")
    add("imports against the exports listed in `drvhost_exports.c`, and runs its")
    add("DriverEntry, PnP and IRP dispatch. A driver that imports a name that is not")
    add("listed as implemented here fails to load with `STATUS_PROCEDURE_NOT_FOUND`, and")
    add("DbgPrint names every unresolved import, so one attempt lists them all.")
    add("")

    total = len(ranked)
    impl_ranked = sum(1 for _, m, n in ranked if (m, n) in implemented)
    add("## Summary")
    add("")
    add(f"- Ranked names in the manifest: {total}")
    add(f"- Ranked and implemented: {impl_ranked} ({100.0 * impl_ranked / total:.1f}%)")
    add(f"- Ranked and missing: {total - impl_ranked}")
    add(f"- Implemented exports in total: {len(implemented)}")
    add(f"- Implemented but not in the ranking: {len(implemented) - impl_ranked}")
    add("")
    add("Per tier (1 = needed by almost every driver, 4 = niche):")
    add("")
    add("| Tier | Ranked | Implemented | Missing |")
    add("|-----:|-------:|------------:|--------:|")
    for tier in sorted({t for t, _, _ in ranked}):
        rows = [(m, n) for t, m, n in ranked if t == tier]
        done = sum(1 for k in rows if k in implemented)
        add(f"| {tier} | {len(rows)} | {done} | {len(rows) - done} |")
    add("")

    add("## Ranked surface")
    add("")
    add("Rank is the position in `tools/ntos_common_imports.txt`. The ranking is the")
    add("author's estimate from driver development practice, not a measured count over")
    add("a driver corpus.")
    add("")
    add("| Rank | Tier | Module | Export | Status | Host symbol |")
    add("|-----:|-----:|--------|--------|--------|-------------|")
    for rank, (tier, module, name) in enumerate(ranked, 1):
        key = (module, name)
        if key in implemented:
            status = "implemented (data)" if name in DATA_EXPORTS else "implemented"
            sym = f"`{implemented[key]}`"
        else:
            status = "missing"
            sym = ""
        add(f"| {rank} | {tier} | {MODULE_NAME[module]} | `{name}` | {status} | {sym} |")
    add("")

    extra = sorted(k for k in implemented if k not in ranked_keys)
    add("## Implemented but not in the ranking")
    add("")
    if not extra:
        add("None.")
    else:
        add("| Module | Export | Host symbol |")
        add("|--------|--------|-------------|")
        for module, name in extra:
            add(f"| {MODULE_NAME[module]} | `{name}` | `{implemented[(module, name)]}` |")
    add("")

    add("## Notes")
    add("")
    add("- Scope: userspace-hosted model on the Linux guest (pthreads, mmap). The host")
    add("  is not yet linked into the personality kernel module.")
    add("- Calling convention: every driver-facing function and data export uses the")
    add("  Microsoft x64 ABI (`__attribute__((ms_abi))`, `DRVCALL` in `drvhost_types.h`).")
    add("- Data exports (`PsThreadType`, `IoFileObjectType`, ...) are object-type pointers")
    add("  and are referenced by drivers as `*PsThreadType`, as in the WDK.")
    add("- Import binding is by exact name within the module the driver names. Ordinal")
    add("  imports fail the load. Imports from modules other than ntoskrnl.exe and hal.dll")
    add("  fail the load.")
    add("- IRQL is tracked per thread. Misuse (for example waiting at DISPATCH_LEVEL with a")
    add("  timeout, or recursive acquisition of a spin lock) bugchecks the host and aborts.")
    add("")
    add("## Layout confidence")
    add("")
    add("The x64 structure layouts that drivers touch directly (`DRIVER_OBJECT`, `DEVICE_OBJECT`, `IRP`,")
    add("`IO_STACK_LOCATION`, `FILE_OBJECT`, `KDPC`, `KEVENT`, `FAST_MUTEX`, `KMUTANT`, `KSEMAPHORE`, `ERESOURCE`,")
    add("the lookaside lists and more) were first written from memory. They are now compared field by field with the")
    add("WDK definitions in Wine's headers (`third_party/wine/include`) by `make -C tests/kernel-drivers layout`;")
    add("the list of measured fields is `tests/kernel-drivers/layout/layout_list.h`. That comparison found and")
    add("fixed errors in `KDPC`, `DEVICE_OBJECT`, `FILE_OBJECT`, `IRP` and the `IO_STACK_LOCATION` parameter")
    add("blocks. A structure that is not in the list has not been compared. The first vendor-driver run is the")
    add("check of the rest.")
    add("")
    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--repo", default=".", help="repository root")
    ap.add_argument("--out", default=None, help="output file (default: docs/status/DRIVERHOST-EXPORTS.md under --repo)")
    ap.add_argument("--check", action="store_true", help="exit 1 if the output file differs from the generated text")
    args = ap.parse_args(argv)
    repo = os.path.abspath(args.repo)
    out = args.out or os.path.join(repo, OUT_REL)
    text = build(repo)
    if args.check:
        try:
            with open(out, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = ""
        if current != text:
            print(f"stale: {out}", file=sys.stderr)
            return 1
        print(f"up to date: {out}")
        return 0
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
