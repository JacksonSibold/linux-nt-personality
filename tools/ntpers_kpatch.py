class Result:
    __slots__ = ("status", "message")

    def __init__(self, status, message=""):
        self.status = status
        self.message = message


class Tree:
    """A kernel tree with an in-memory plan on top of the files on disk."""

    def __init__(self, root):
        self.root = pathlib.Path(root)
        self._orig = {}
        self._cur = {}

    def original(self, rel):
        if rel not in self._orig:
            p = self.root / rel
            self._orig[rel] = p.read_bytes() if p.is_file() else None
        return self._orig[rel]

    def current(self, rel):
        if rel in self._cur:
            return self._cur[rel]
        return self.original(rel)

    def set(self, rel, data):
        self._cur[rel] = data

    def changed(self):
        out = {}
        for rel, data in self._cur.items():
            if data != self.original(rel):
                out[rel] = data
        return out


class Edit:
    def __init__(self, eid, path, desc, gap=None):
        self.eid = eid
        self.path = path
        self.desc = desc
        self.gap = gap

    def blocked(self, why):
        gap = " (BUILD-RECIPE %s)" % self.gap if self.gap else ""
        return Result(BLOCKED, why + gap)

    def run(self, tree):  # pragma: no cover - abstract
        raise NotImplementedError


class CopyEdit(Edit):
    def __init__(self, eid, src, dst, desc, gap=None):
        Edit.__init__(self, eid, dst, desc, gap)
        self.src = pathlib.Path(src)

    def run(self, tree):
        if not self.src.is_file():
            return self.blocked("source file missing: %s" % self.src)
        # A Windows checkout is CRLF (BUILD-RECIPE G23). The kernel tree is LF,
        # so copies are normalised; the anchors are written against LF text.
        raw = self.src.read_bytes()
        data = raw.replace(b"\r\n", b"\n")
        same = tree.original(self.path) == data
        tree.set(self.path, data)
        note = " (CRLF normalised to LF)" if data != raw else ""
        return Result(APPLIED if same else APPLICABLE,
                      "copied from %s%s" % (self.src.name, note))


class WriteEdit(Edit):
    def __init__(self, eid, dst, data, desc, gap=None):
        Edit.__init__(self, eid, dst, desc, gap)
        self.data = data

    def run(self, tree):
        same = tree.original(self.path) == self.data
        tree.set(self.path, self.data)
        return Result(APPLIED if same else APPLICABLE, "written whole")


class InsertEdit(Edit):
    def __init__(self, eid, path, anchor, text, marker, desc, gap=None,
                 where="after", expect_after=None, precheck=None):
        Edit.__init__(self, eid, path, desc, gap)
        self.anchor = re.compile(anchor, re.M)
        self.text = text
        self.marker = marker
        self.where = where
        self.expect_after = re.compile(expect_after, re.M) if expect_after else None
        self.precheck = precheck

    def run(self, tree):
        cur = tree.current(self.path)
        if cur is None:
            return self.blocked("file missing in tree: %s" % self.path)
        text = cur.decode(ENC)
        if self.marker in text:
            return Result(APPLIED, "already present")
        # A copy earlier in this run may have reset the file; the edit is then
        # re-made, but the status still reflects the file on disk.
        on_disk = tree.original(self.path)
        was_there = on_disk is not None and self.marker in on_disk.decode(ENC)
        hits = list(self.anchor.finditer(text))
        if len(hits) != 1:
            return self.blocked(
                "anchor /%s/ matches %d times in %s, expected exactly 1"
                % (self.anchor.pattern, len(hits), self.path))
        m = hits[0]
        if self.expect_after is not None and not self.expect_after.match(text, m.end()):
            return self.blocked(
                "text after the anchor in %s is not /%s/"
                % (self.path, self.expect_after.pattern))
        if self.precheck is not None:
            why = self.precheck(text, tree)
            if why:
                return self.blocked(why)
        pos = m.end() if self.where == "after" else m.start()
        new = text[:pos] + self.text + text[pos:]
        tree.set(self.path, new.encode(ENC))
        if was_there:
            return Result(APPLIED, "present on disk, re-made after a copy")
        return Result(APPLICABLE, "inserted %s the anchor" % self.where)


class AppendEdit(Edit):
    def __init__(self, eid, path, text, marker, desc, gap=None):
        Edit.__init__(self, eid, path, desc, gap)
        self.text = text
        self.marker = marker

    def run(self, tree):
        cur = tree.current(self.path)
        if cur is None:
            return self.blocked("file missing in tree: %s" % self.path)
        text = cur.decode(ENC)
        if self.marker in text:
            return Result(APPLIED, "already present")
        on_disk = tree.original(self.path)
        was_there = on_disk is not None and self.marker in on_disk.decode(ENC)
        if text and not text.endswith("\n"):
            text += "\n"
        tree.set(self.path, (text + self.text).encode(ENC))
        if was_there:
            return Result(APPLIED, "present on disk, re-made after a copy")
        return Result(APPLICABLE, "appended")


class TodoEdit(Edit):
    def __init__(self, eid, path, desc, gap, reason):
        Edit.__init__(self, eid, path, desc, gap)
        self.reason = reason

    def run(self, tree):
        return Result(TODO, "%s: %s (see %s %s)"
                      % (self.path, self.reason, GAPS_DOC, self.gap))


def tif_bit_free(name, bit):
    """Precheck: the bit is in range and no other TIF_ define uses it."""
    def check(text, _tree):
        for m in re.finditer(r"^#define[ \t]+(TIF_\w+)[ \t]+(\d+)\b", text, re.M):
            if int(m.group(2)) == bit and m.group(1) != name:
                return ("%s: bit %d is already used by %s in %s"
                        % (name, bit, m.group(1), THREAD_INFO))
        return None
    return check


def em_value_free(_text, tree):
    """Precheck: elf-em.h, when present, does not define EM_NTX86_64's value."""
    raw = tree.original(ELF_EM_H)
    if raw is None:
        return None
    for m in re.finditer(r"^#define[ \t]+(EM_\w+)[ \t]+(0x[0-9a-fA-F]+|\d+)\b",
                         raw.decode(ENC), re.M):
        if int(m.group(2), 0) == NT_EM_VALUE:
            return ("EM value 0x%04X is already %s in %s"
                    % (NT_EM_VALUE, m.group(1), ELF_EM_H))
    return None


def nt_resolution(project):
    """Return (chosen, objects): the NT source files the build needs.

    chosen maps each file name to (path, origin) where origin is "arch" or
    "src". The walk starts from the object list in arch/x86/nt/Makefile and
    follows quoted #include lines. Names in ARCH_WINS come from arch; every
    other name found in src/kernel/nt/ comes from src, which overwrites the arch
    copy the way rebuild_kdir.sh does.
    """
    arch = project / "arch/x86/nt"
    src = project / "src/kernel/nt"
    mk = (arch / "Makefile").read_text(encoding=ENC)
    objects = OBJ_RE.findall(mk)
    queue = [o + ".c" for o in objects]
    chosen = {}
    seen = set()
    while queue:
        name = queue.pop(0)
        if name in seen:
            continue
        seen.add(name)
        if name in ARCH_WINS or not (src / name).is_file():
            cand, origin = arch / name, "arch"
        else:
            cand, origin = src / name, "src"
        if not cand.is_file():
            continue  # generated (stubs.c) or absent; handled by the caller
        chosen[name] = (cand, origin)
        for inc in INC_RE.findall(cand.read_text(encoding=ENC)):
            queue.append(inc)
    return chosen, objects


def build_plan(project):
    """Return (edits, warnings) for a project tree. Order matters: copies first."""
    project = pathlib.Path(project)
    arch = project / "arch/x86/nt"
    edits = []
    warnings = []
    counter = [0]

    def eid():
        counter[0] += 1
        return "E%02d" % counter[0]

    chosen, _objects = nt_resolution(project)
    overrides = {n: p for n, (p, o) in chosen.items() if o == "src"}

    # 1. arch/x86/nt/ as tracked, except names the src copy overrides.
    if arch.is_dir():
        for f in sorted(arch.iterdir()):
            if f.is_file() and f.name not in overrides:
                edits.append(CopyEdit(eid(), f, "arch/x86/nt/" + f.name,
                                      "tracked NT source"))
    # 2. src/kernel/nt/ files the build needs (BUILD-RECIPE 4.2).
    for name in sorted(overrides):
        if (arch / name).is_file():
            warnings.append(
                "WARN G24: src/kernel/nt/%s overwrites arch/x86/nt/%s "
                "(rebuild_kdir.sh rule; which copy is canonical is open)"
                % (name, name))
        edits.append(CopyEdit(eid(), overrides[name],
                              "arch/x86/nt/" + name,
                              "src/kernel/nt/%s (build dependency)" % name))
    # 3. generated, empty stubs.c (BUILD-RECIPE 4.4).
    edits.append(WriteEdit(eid(), "arch/x86/nt/stubs.c", b"",
                           "generated empty stubs (BUILD-RECIPE 4.4)"))
    # 4. ntdll headers and the PE loader (BUILD-RECIPE 4.6, 4.7).
    ntdll = project / "src/ntdll"
    if ntdll.is_dir():
        for h in sorted(ntdll.glob("*.h")):
            edits.append(CopyEdit(eid(), h, "arch/ntdll/" + h.name,
                                  "ntdll header"))
    edits.append(CopyEdit(eid(), project / "src/kernel/fs/binfmt_pe.c",
                          "fs/binfmt_pe.c", "PE loader"))

    # 5. Kconfig, Kbuild and fs wiring (BUILD-RECIPE 5a-5e).
    edits.append(WriteEdit(eid(), "arch/x86/Kconfig.nt",
                           KCONFIG_NT.encode(ENC), "NT_PERSONALITY Kconfig"))
    edits.append(InsertEdit(
        eid(), KCONFIG, r"^endif # HYPERVISOR_GUEST\n", "\nsource \"arch/x86/Kconfig.nt\"\n",
        'source "arch/x86/Kconfig.nt"', "source line after HYPERVISOR_GUEST",
        gap="G5"))
    edits.append(AppendEdit(eid(), KBUILD,
                            "obj-$(CONFIG_NT_PERSONALITY) += nt/\n",
                            "obj-$(CONFIG_NT_PERSONALITY) += nt/",
                            "descend into nt/", gap="G5"))
    edits.append(AppendEdit(eid(), FS_MAKEFILE,
                            "obj-$(CONFIG_BINFMT_PE)\t+= binfmt_pe.o\n",
                            "binfmt_pe.o", "build binfmt_pe.o", gap="G5"))
    edits.append(AppendEdit(eid(), FS_KCONFIG_BINFMT, FS_BINFMT_PE,
                            "config BINFMT_PE", "BINFMT_PE symbol", gap="G5"))

    # 6. thread_info.h flags (BUILD-RECIPE 5f, G4). Bits are checked, not chosen.
    edits.append(InsertEdit(
        eid(), THREAD_INFO, r"^#define TIF_ADDR32\b.*\n",
        "#define TIF_NTABI\t\t%d\t/* task uses the NT system-call ABI */\n" % NTABI_BIT,
        "#define TIF_NTABI", "TIF_NTABI flag bit %d" % NTABI_BIT,
        gap="G4", precheck=tif_bit_free("TIF_NTABI", NTABI_BIT)))
    edits.append(InsertEdit(
        eid(), THREAD_INFO, r"^#define TIF_ADDR32\b.*\n",
        "#define TIF_NTSUSPEND\t%d\t/* NT thread suspend */\n" % NTSUSPEND_BIT,
        "#define TIF_NTSUSPEND", "TIF_NTSUSPEND flag bit %d" % NTSUSPEND_BIT,
        gap="G4", precheck=tif_bit_free("TIF_NTSUSPEND", NTSUSPEND_BIT)))
    edits.append(InsertEdit(
        eid(), THREAD_INFO, r"^#define _TIF_FORCED_TF\b.*\n",
        "#define _TIF_NTABI\t\tBIT(TIF_NTABI)\n",
        "#define _TIF_NTABI", "_TIF_NTABI mask", gap="G4"))
    edits.append(InsertEdit(
        eid(), THREAD_INFO, r"^#define _TIF_FORCED_TF\b.*\n",
        "#define _TIF_NTSUSPEND\tBIT(TIF_NTSUSPEND)\n",
        "#define _TIF_NTSUSPEND", "_TIF_NTSUSPEND mask", gap="G4"))

    # 7. task_struct and fork (BUILD-RECIPE 5g, 5h; object.c reads nt_thread).
    edits.append(InsertEdit(
        eid(), SCHED_H,
        r"^\t/\* CPU-specific state of this task: \*/\n\tstruct thread_struct\s+thread;\n",
        "\n#ifdef CONFIG_NT_PERSONALITY\n\tvoid\t\t\t\t*nt_thread;\n#endif\n",
        "*nt_thread;", "task_struct nt_thread", gap="G5"))
    edits.append(InsertEdit(
        eid(), FORK_C, r"^\terr = arch_dup_task_struct\(tsk, orig\);\n",
        "#ifdef CONFIG_NT_PERSONALITY\n\ttsk->nt_thread = NULL;\n#endif\n",
        "tsk->nt_thread = NULL", "clear nt_thread after the task copy",
        gap="G5"))

    # 8. Syscall dispatch (BUILD-RECIPE 5i, G6): one form, the NT branch in
    # do_syscall_64() after add_random_kstack_offset().
    edits.append(InsertEdit(
        eid(), SYSCALL_64,
        r"^__visible noinstr bool do_syscall_64\(struct pt_regs \*regs, int nr\)\n",
        PROTOTYPES, "void do_nt_syscall(struct pt_regs *regs, unsigned int ssn);",
        "NT dispatch prototypes", gap="G6", where="before",
        expect_after=r"\{\n"))
    edits.append(InsertEdit(
        eid(), SYSCALL_64, r"^\tadd_random_kstack_offset\(\);\n",
        DISPATCH, "test_thread_flag(TIF_NTABI)", "NT syscall branch",
        gap="G6"))

    # 9. Seccomp and audit arch (patch 0002; G3).
    edits.append(InsertEdit(
        eid(), AUDIT_H, r"^#define AUDIT_ARCH_X86_64\b.*\n", AUDIT_DEFS,
        "#define AUDIT_ARCH_NTX86_64", "AUDIT_ARCH_NTX86_64 and EM_NTX86_64",
        gap="G3", precheck=em_value_free))
    edits.append(InsertEdit(
        eid(), SYSCALL_H,
        r"^\t/\* x32 tasks should be considered AUDIT_ARCH_X86_64\. \*/\n",
        ARCH_GET, "AUDIT_ARCH_NTX86_64",
        "syscall_get_arch reports the NT arch", gap="G3", where="before"))

    # 10. nt_banner_init has a caller now (BUILD-RECIPE G10).
    edits.append(InsertEdit(
        eid(), KSTUBS, r"^#include <linux/kernel\.h>\n",
        "#include <linux/init.h>\n", "#include <linux/init.h>",
        "init.h for the banner initcall", gap="G10"))
    edits.append(AppendEdit(eid(), KSTUBS, BANNER_CALLER,
                            "late_initcall(nt_banner_initcall)",
                            "boot-time caller for nt_banner_init", gap="G10"))

    # 11. Still undecided. Fails every run until BUILD-RECIPE G3 is closed.
    edits.append(TodoEdit(
        eid(), "arch/x86/entry/nt/enter.c",
        "NT entry hooks (patch 0002, enter.c)", "G3",
        "not applied: the NT branch calls no seccomp, audit or ptrace hook; "
        "enter.c needs syscall_trace_enter(), which is not a declared kernel "
        "API in this repository, and it needs an arch/x86/entry Makefile line"))
    return edits, warnings


def check_tree(tree_root):
    root = pathlib.Path(tree_root)
    return (root / "Makefile").is_file() and (root / "arch/x86").is_dir()


def write_changes(tree):
    for rel, data in sorted(tree.changed().items()):
        dst = tree.root / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        tmp = dst.with_name(dst.name + ".ntpers-tmp")
        tmp.write_bytes(data)
        os.replace(tmp, dst)
    return len(tree.changed())


def run_plan(project, tree_root, check, allow_todo, out):
    """Plan every edit, report each one, and write only when nothing blocks."""
    edits, warnings = build_plan(project)
    tree = Tree(tree_root)
    counts = {APPLIED: 0, APPLICABLE: 0, BLOCKED: 0, TODO: 0}
    blockers = []
    results = [(e, e.run(tree)) for e in edits]
    # When a run writes nothing, every edit that did not block is in place.
    nothing_to_write = not tree.changed()
    for e, r in results:
        status = r.status
        if status == APPLICABLE and nothing_to_write:
            status = APPLIED
        counts[status] += 1
        out("[%-10s] %s %s: %s%s" % (status, e.eid, e.path, e.desc,
                                     (" -- " + r.message) if r.message else ""))
        if status in (BLOCKED, TODO):
            blockers.append((e, Result(status, r.message)))
    for w in warnings:
        out(w)
    out("summary: %d applied, %d applicable, %d blocked, %d todo"
        % (counts[APPLIED], counts[APPLICABLE], counts[BLOCKED], counts[TODO]))
    hard = [b for b in blockers if b[1].status == BLOCKED]
    todo = [b for b in blockers if b[1].status == TODO]
    if check:
        if blockers:
            out("CHECK FAILED: %d blocked, %d todo" % (len(hard), len(todo)))
            return 1
        out("CHECK OK: every edit is applied or applicable (%d changes pending)"
            % len(tree.changed()))
        return 0
    if hard or (todo and not allow_todo):
        out("NOT APPLIED: nothing was written (%d blocked, %d todo)"
            % (len(hard), len(todo)))
        return 1
    written = write_changes(tree)
    out("APPLIED: %d files written to %s" % (written, tree.root))
    return 0


def selftest():
    """Exercise the edit primitives on a tiny fixture. Returns 0 or 1."""
    fails = []

    def expect(label, cond):
        if not cond:
            fails.append(label)
            print("selftest FAIL: %s" % label)

    with tempfile.TemporaryDirectory() as d:
        root = pathlib.Path(d)
        (root / "f.h").write_bytes(
            b"#define TIF_ADDR32\t\t28\t/* x */\n#define _TIF_FORCED_TF\tBIT(TIF_FORCED_TF)\n")
        tree = Tree(root)
        ins = InsertEdit("S1", "f.h", r"^#define TIF_ADDR32\b.*\n",
                         "#define TIF_NTABI\t29\n", "#define TIF_NTABI", "t",
                         gap="G4", precheck=tif_bit_free("TIF_NTABI", 29))
        r = ins.run(tree)
        expect("insert is applicable", r.status == APPLICABLE)
        write_changes(tree)
        expect("second run is applied", InsertEdit(
            "S1", "f.h", r"^#define TIF_ADDR32\b.*\n", "x\n", "#define TIF_NTABI",
            "t").run(Tree(root)).status == APPLIED)
        r = InsertEdit("S2", "f.h", r"^#define NOPE\b.*\n", "x\n", "x-marker",
                       "t", gap="G4").run(Tree(root))
        expect("missing anchor is blocked", r.status == BLOCKED and "G4" in r.message)
        r = InsertEdit("S3", "f.h", r"^#define _TIF_FORCED_TF\b.*\n", "y\n",
                       "y-marker", "t", gap="G4",
                       precheck=tif_bit_free("TIF_NTSUSPEND", 28)).run(Tree(root))
        expect("taken bit is blocked", r.status == BLOCKED and "TIF_ADDR32" in r.message)
        r = AppendEdit("S4", "missing.mk", "x\n", "x", "t").run(Tree(root))
        expect("missing file is blocked", r.status == BLOCKED)
    print("selftest: %s" % ("FAIL" if fails else "PASS"))
    return 1 if fails else 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Apply the NT personality's kernel-tree edits (anchored, idempotent).")
    ap.add_argument("--tree", help="kernel source tree to modify")
    ap.add_argument("--project", default=str(PROJECT_ROOT),
                    help="repository root (default: parent of tools/)")
    ap.add_argument("--check", action="store_true",
                    help="report each edit and change nothing")
    ap.add_argument("--allow-todo", action="store_true",
                    help="apply everything else when only todo edits remain")
    ap.add_argument("--selftest", action="store_true",
                    help="run the built-in primitive tests")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    if not args.tree:
        ap.error("--tree is required (or use --selftest)")
    if not check_tree(args.tree):
        print("error: %s is not a kernel tree (no Makefile or arch/x86)" % args.tree,
              file=sys.stderr)
        return 2
    project = pathlib.Path(args.project)
    if not (project / "arch/x86/nt/Makefile").is_file():
        print("error: %s is not the repository root (no arch/x86/nt/Makefile)" % project,
              file=sys.stderr)
        return 2
    return run_plan(project, args.tree, args.check, args.allow_todo,
                    lambda s: print(s, flush=True))


if __name__ == "__main__":
    sys.exit(main())
