#!/usr/bin/env python3
"""
ntpers_kpatch.py - apply every kernel-tree change the NT personality needs.

The NT personality is built into a Linux 6.18 tree in the order given by
docs/vm/BUILD-RECIPE.md, sections 4 and 5. The patch files under
src/kernel/patches/ do not apply (BUILD-RECIPE G2, G3), and the wiring used
to live only in vm/rebuild_kdir.sh. This script makes the same changes
directly, one anchored edit at a time.

Edit kinds:
  copy    a project file is copied over a tree file
  write   a generated or inline file is written whole
  insert  text is inserted before or after a regex anchor
  append  text is appended unless its marker is already present
  todo    the change is not decided yet; it fails the run and names the gap

An anchor must match exactly once in the current text of its file, and the
text next to it must match any expect-context pattern. A missing or ambiguous
anchor, a bit number already in use, or a missing file stops the run with a
message that names the file and the BUILD-RECIPE gap. Nothing is written
unless every edit is applied or applicable.

Usage:
  python3 tools/ntpers_kpatch.py --tree KDIR             apply; refuses on any block or todo
  python3 tools/ntpers_kpatch.py --tree KDIR --check     report every edit, change nothing
  python3 tools/ntpers_kpatch.py --tree KDIR --allow-todo
                                                        apply, skipping todo edits only
  python3 tools/ntpers_kpatch.py --selftest              built-in primitive tests

Options:
  --project PATH   repository root (default: the parent of tools/)

Exit status: 0 applied (or --check with nothing blocked), 1 blocked or todo
edits remain, 2 usage error or the tree is not a kernel tree.
"""
